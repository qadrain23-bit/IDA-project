"""One-off helper: infer column types from the 7 source CSVs and write
src/pipeline/sql/01_staging_ddl.sql. Run again only if the source layout changes."""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from pipeline.config import SOURCE_DIR, SOURCES  # noqa: E402


def pg_type(name: str, s: pd.Series) -> str:
    s = s.dropna()
    if name.endswith("TimestampUTC"):
        return "TIMESTAMPTZ"
    if name.endswith("Date") or name.endswith("Month"):
        return "DATE"
    if name in ("GTIN14", "SSCC18") or name.endswith("GLN") or name.endswith("ID"):
        return "TEXT"
    num = pd.to_numeric(s, errors="coerce")
    if len(s) and num.notna().all():
        return "BIGINT" if (num % 1 == 0).all() and not s.str.contains(r"\.").any() else "NUMERIC(14,4)"
    return "TEXT"


out = ["-- Staging (ODS) layer in Postgres. Generated by scripts/build_staging_ddl.py",
       "CREATE SCHEMA IF NOT EXISTS staging;", ""]
for key, (fname, table, pk, _anchor) in SOURCES.items():
    df = pd.read_csv(SOURCE_DIR / fname, dtype=str)
    cols = [f'    "{c}" {pg_type(c, df[c])}' for c in df.columns]
    cols += ['    "_load_id" BIGINT NOT NULL', '    "_source_file" TEXT',
             '    "_event_created_at" TIMESTAMPTZ',
             '    "_ingested_at" TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()']
    out.append(f"CREATE TABLE IF NOT EXISTS staging.{table} (\n" + ",\n".join(cols) + "\n);")
    out.append(f"CREATE INDEX IF NOT EXISTS ix_{table}_load ON staging.{table} (_load_id);")
    out.append("")
Path("src/pipeline/sql/01_staging_ddl.sql").write_text("\n".join(out))
print("written")
